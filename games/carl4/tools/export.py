"""Writes the sprite atlases + Lua metadata into games/carl4/sprites/, plus preview sheets/GIFs in art/.
    python3 tools/export.py
"""
import sys, os, math
sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image
from spr import to_img, sheet, gif
import carl, humans, guns

ROOT = os.path.join(os.path.dirname(__file__), '..')
OUT = os.path.join(ROOT, 'sprites'); os.makedirs(OUT, exist_ok=True)
PREV = os.path.join(ROOT, 'art'); os.makedirs(PREV, exist_ok=True)


def lua(v, ind=''):
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if isinstance(k, str) and k.isidentifier() else f'[{json_key(k)}]'
            items.append(f'{ind}  {key} = {lua(x, ind + "  ")}')
        return '{\n' + ',\n'.join(items) + f'\n{ind}}}'
    if isinstance(v, (list, tuple)): return '{ ' + ', '.join(lua(x, ind) for x in v) + ' }'
    if isinstance(v, bool): return 'true' if v else 'false'
    if isinstance(v, str): return '"' + v.replace('"', '\\"') + '"'
    if v is None: return 'nil'
    return str(v)


def json_key(k): return f'"{k}"' if isinstance(k, str) else str(k)


def atlas(name, frames, anims, legend, w, h, origin):
    names = list(frames.keys())
    cols = 16
    rows = math.ceil(len(names) / cols)
    im = Image.new('RGBA', (cols * w, rows * h))
    hands = {}
    for i, n in enumerate(names):
        g, hand, pose = frames[n]
        im.alpha_composite(to_img(g, legend), ((i % cols) * w, (i // cols) * h))
        if hand: hands[i] = {'x': hand[0], 'y': hand[1], 'pose': pose or 'none'}
    im.save(os.path.join(OUT, name + '.png'))
    idx = {n: i for i, n in enumerate(names)}
    meta = {'w': w, 'h': h, 'cols': cols, 'rows': rows, 'origin': list(origin),
            'anims': {a: {'frames': [idx[f] for f in d['frames']], 'ms': d['ms'], 'loop': d['loop']} for a, d in anims.items()},
            'hands': hands}
    open(os.path.join(OUT, name + '.lua'), 'w').write('-- generated by tools/export.py\nreturn ' + lua(meta) + '\n')
    sheet([(n, frames[n][0]) for n in names], legend, os.path.join(PREV, name + '_sheet.png'), k=4, cols=16)
    for a in ('se_idle', 'se_run', 'se_walk', 'ne_run', 'se_die', 'se_fire', 'se_slam'):
        if a in anims: gif([frames[f][0] for f in anims[a]['frames']], legend, os.path.join(PREV, f'{name}_{a}.gif'), anims[a]['ms'])
    print(f'{name}: {len(names)} frames, {len(anims)} anims')


f, a = carl.build()
atlas('carl', f, a, carl.LEGEND, carl.W, carl.H, (20, 34))
for v, boss in humans.VARIANTS.items():
    f, a = humans.build_variant(v, boss)
    atlas(v, f, a, humans.PAL[v], humans.W, humans.H, (25, 48))

# Gun overlays: one cell per maker/kind/pose, grip at (10, 9).
gf = guns.build()
cols = 18
rows = math.ceil(len(gf) / cols)
im = Image.new('RGBA', (cols * guns.CELL_W, rows * guns.CELL_H))
index = {}
for i, (n, g, leg) in enumerate(gf):
    im.alpha_composite(to_img(g, leg), ((i % cols) * guns.CELL_W, (i // cols) * guns.CELL_H))
    index[n] = i
im.save(os.path.join(OUT, 'guns.png'))
open(os.path.join(OUT, 'guns.lua'), 'w').write('-- generated by tools/export.py\nreturn ' + lua(
    {'w': guns.CELL_W, 'h': guns.CELL_H, 'cols': cols, 'rows': rows, 'grip': [10, 9], 'index': index}) + '\n')
print('guns:', len(gf))

# Dialogue portraits: one row per speaker (idle, talk, blink), 40x40 each.
import portraits
pf = portraits.build()
nf = len(portraits.FRAMES)
im = Image.new('RGBA', (nf * portraits.S, len(portraits.PORTRAITS) * portraits.S))
rows = {}
for i, (n, f, g, pal) in enumerate(pf):
    im.alpha_composite(to_img(g, pal), ((i % nf) * portraits.S, (i // nf) * portraits.S))
    rows[n] = i // nf
im.save(os.path.join(OUT, 'portraits.png'))
open(os.path.join(OUT, 'portraits.lua'), 'w').write('-- generated by tools/export.py\nreturn ' + lua(
    {'size': portraits.S, 'cols': nf, 'rows': len(portraits.PORTRAITS), 'frames': portraits.FRAMES, 'index': rows}) + '\n')
print('portraits:', len(rows))
